import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { test } from 'node:test';
import express from 'express';
import { Pool } from 'pg';
import { ZodError } from 'zod';
import { migrate } from '../dist/migrate.js';
import { ArticleService } from '../dist/articles.js';
import { CmsService } from '../dist/cms.js';
import { ZhiyueDeviceService } from '../dist/zhiyue-device.js';
import { ZhiyueContentService } from '../dist/zhiyue-content.js';
import { createZhiyueDeviceRouter } from '../dist/zhiyue-http.js';

const db = process.env.ZHIYUE_TEST_DATABASE_URL;
test('设备状态筛选、发布快照、草稿检索分页、账号隔离及版本音频票据', { skip: !db }, async (t) => {
  const target = new URL(db);
  assert.equal(target.pathname, '/zhiyue_integration_test');
  assert.ok(['127.0.0.1','localhost','[::1]'].includes(target.hostname));
  await migrate(db);
  const pool = new Pool({ connectionString: db });
  const owners = [randomUUID(), randomUUID()];
  const articles = new ArticleService(pool), cms = new CmsService(pool, articles), devices = new ZhiyueDeviceService(pool);
  const content = new ZhiyueContentService(pool);
  let server;
  t.after(async () => {
    if (server) await new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); });
    await pool.query('DELETE FROM ac_accounts WHERE id=ANY($1::uuid[])', [owners]); await pool.end();
  });
  for (const id of owners) await pool.query("INSERT INTO ac_accounts(id,login,display_name,password_hash,status) VALUES($1,$2,'Synthetic status','fixture','active')", [id, 'status-test-' + id]);
  const category = await cms.createTaxonomy(owners[0], 'category', { name: '草稿专属', slug: 'draft-only' });
  const create = (owner, title, categoryId = null) => cms.create(owner, { title, text: '保存的原文。', cms: { slug: 'fixture-' + randomUUID(), summary: '', categoryId, tagIds: [] } });
  const published = await create(owners[0], '发布标题');
  await cms.publish(owners[0], published.id, { expectedRevision: published.revision, expectedCmsRevision: published.cms.revision, expectedAudioId: null });
  await articles.update(owners[0], published.id, { title: '尚未发布的修改', text: '不应代替发布快照', expectedRevision: published.revision });
  const drafts = [];
  for (let i=0;i<13;i++) drafts.push(await create(owners[0], '草稿' + i, category.id));
  const privateDraft = await create(owners[1], '另一个账号的草稿');
  const request = await devices.start(randomUUID()); await devices.approve(owners[0], request.user_code);
  const grant = await devices.claim(request.device_code); await devices.confirm(grant.refresh_token);
  const app = express();
  app.use('/v1/zhiyue', createZhiyueDeviceRouter(devices,cms,'https://cms.example.test',()=>true,undefined,content));
  app.use((error,_req,res,_next)=>res.status(error instanceof ZodError ? 400 : error.status ?? 500).json({ code: error.code ?? error.error ?? 'BAD_REQUEST' }));
  server = app.listen(0,'127.0.0.1'); await once(server,'listening');
  const base = 'http://127.0.0.1:' + server.address().port;
  const call = (path, body, headers = {}) => fetch(base + '/v1/zhiyue' + path, { method: body === undefined ? 'GET':'POST',
    headers: { Authorization: 'Bearer '+grant.access_token, ...(body === undefined ? {} : {'Content-Type':'application/json'}), ...headers },
    body: body === undefined ? undefined : JSON.stringify(body) });
  const json = async (path, body) => { const response = await call(path,body); const data = await response.json(); assert.equal(response.status,200,JSON.stringify(data)); return data; };
  const defaultPage = await json('/read/articles');
  assert.equal(defaultPage.total,1); assert.equal(defaultPage.items[0].title,'发布标题');
  assert.equal((await json('/read/articles/'+published.id)).text,'保存的原文。');
  assert.equal((await call('/read/articles/'+drafts[0].id)).status,404);
  const draftPage = await json('/read/articles?status=draft');
  assert.equal(draftPage.total,13); assert.equal(draftPage.items.length,12);
  assert.ok(draftPage.items.every((item)=>item.status==='draft' && item.publishedAt===null && item.updatedAt && !('text' in item)));
  assert.equal(draftPage.navigation.categories[0].name,'草稿专属');
  assert.equal(draftPage.items[0].category.revision,category.revision);
  assert.equal(draftPage.navigation.categories[0].articleCount,13);
  const next = await json('/read/articles?status=draft&offset=12');
  assert.equal(next.items.length,1); assert.ok(!draftPage.items.some((item)=>item.id===next.items[0].id));
  const all = await json('/read/articles?status=all&limit=20');
  assert.equal(all.total,14); assert.equal(new Set(all.items.map((item)=>item.id)).size,14);
  assert.equal(all.items.find((item)=>item.id===published.id).title,'发布标题');
  const search = await json('/read/search',{text:'草稿专属分类',status:'draft'});
  assert.equal(search.total,13); assert.equal(search.filters.status,'draft'); assert.equal(search.filters.category,category.id);
  const publishedSearch = await json('/read/search',{text:'草稿专属分类'});
  assert.equal(publishedSearch.total,0);
  const detail = await json('/read/articles/'+drafts[0].id+'?status=draft');
  assert.equal(detail.text,'保存的原文。'); assert.equal(detail.status,'draft');
  for (const status of ['draft','all']) assert.equal((await call('/read/articles/'+privateDraft.id+'?status='+status)).status,404);
  assert.equal((await call('/read/articles?status=invalid')).status,400);
  assert.equal((await call('/read/articles?status=draft&q=%00')).status,400);
  assert.equal((await call('/read/search',{text:'草稿',status:'invalid'})).status,400);
  const audioId = randomUUID(), bytes = Buffer.from([1,2,3,4,5,6,7,8]);
  await pool.query('INSERT INTO wb_article_audio(article_id,generation_seq,metadata,data) VALUES($1,1,$2,$3)',[drafts[0].id,{audioId},bytes]);
  const audioDetail = await json('/read/articles/'+drafts[0].id+'?status=draft');
  assert.equal(audioDetail.hasAudio,true); assert.equal(audioDetail.releaseId,audioId);
  const ticketPath = '/read/drafts/'+drafts[0].id+'/audio-ticket';
  const ticket = await json(ticketPath,{audioId});
  const mediaPath = new URL(ticket.url).pathname.replace('/v1/zhiyue','');
  const media = await call(mediaPath,undefined,{Range:'bytes=2-5'});
  assert.equal(media.status,206); assert.equal(media.headers.get('Content-Range'),'bytes 2-5/8');
  assert.deepEqual(Buffer.from(await media.arrayBuffer()),bytes.subarray(2,6));
  assert.equal((await call('/read/drafts/'+privateDraft.id+'/audio-ticket',{audioId})).status,404);
  const replacement = randomUUID();
  await pool.query('UPDATE wb_article_audio SET metadata=$2 WHERE article_id=$1',[drafts[0].id,{audioId:replacement}]);
  assert.equal((await call(mediaPath)).status,404);
  assert.equal((await call(ticketPath,{audioId})).status,404);
  const currentTicket = await json(ticketPath,{audioId:replacement});
  const currentPath = new URL(currentTicket.url).pathname.replace('/v1/zhiyue','');
  const publishedDraft = await cms.publish(owners[0],drafts[0].id,{expectedRevision:drafts[0].revision,expectedCmsRevision:drafts[0].cms.revision,expectedAudioId:null});
  assert.equal((await call(currentPath)).status,404);
  assert.equal((await call('/read/articles/'+drafts[0].id+'?status=draft')).status,404);
  const restored = await cms.unpublish(owners[0],drafts[0].id,{expectedRevision:drafts[0].revision,expectedCmsRevision:publishedDraft.cmsRevision + 1});
  assert.equal((await json('/read/articles/'+restored.id+'?status=draft')).status,'draft');
  await devices.revoke(owners[0],grant.binding_id);
  assert.equal((await call(currentPath)).status,401);
  assert.equal((await call('/read/articles?status=draft')).status,401);
});
